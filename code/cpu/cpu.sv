
module cpu (
  input  logic [31:0] instrF,
  output logic [15:0] pc,
);
  //////////////////////////////////////////////////////////////////////////////////////
  // DECODE
  //////////////////////////////////////////////////////////////////////////////////////
  logic [3:0][7:0] instrD;

  flopenr instrBuf(clk, flush, ~stall, instrF, instrD);

  ctrl ctrl(.instr(instrD), .instrSz);

  flopen pcflop(clk, ~stall, pcNext, pc);
  always_comb 
    case(pcSel):
      PC_ADD: pcNext = pc + instrSz;
      default: pcNext = 'x;
    endcase


  //////////////////////////////////////////////////////////////////////////////////////
  // MEMORY
  //////////////////////////////////////////////////////////////////////////////////////

  

  //////////////////////////////////////////////////////////////////////////////////////
  // EXECUTE
  //////////////////////////////////////////////////////////////////////////////////////

  

endmodule